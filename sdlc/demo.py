"""`python3 -m sdlc demo <dir>` — build a sample repository that exercises the whole loop.

Every artifact state the web app shows is reached through the real code path (new, submit,
approve, bands) and committed with the author and time a real team would leave: the agent
drafts and submits, named people approve. All names and numbers are sample data.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import subprocess
from pathlib import Path

from . import artifacts, bands, workitems

PKG_ROOT = Path(__file__).resolve().parent.parent
AGENT = ("Claude", "noreply@anthropic.com")
PEOPLE = {
    "po": ("Dana Park", "dana@example.com"),
    "arch": ("Min Seo", "min@example.com"),
    "lead": ("Jun Lee", "jun@example.com"),
    "sec": ("Sam Choi", "sam@example.com"),
}
START = dt.datetime(2026, 9, 1, 9, 0, tzinfo=dt.timezone.utc)


class Demo:
    def __init__(self, root: Path):
        self.root = root
        self.clock = START

    def git(self, *args: str, who=AGENT) -> str:
        stamp = self.clock.isoformat()
        env = {**os.environ, "GIT_AUTHOR_NAME": who[0], "GIT_AUTHOR_EMAIL": who[1], "GIT_AUTHOR_DATE": stamp,
               "GIT_COMMITTER_NAME": who[0], "GIT_COMMITTER_EMAIL": who[1], "GIT_COMMITTER_DATE": stamp}
        return subprocess.run(["git", *args], cwd=self.root, env=env, check=True, capture_output=True, text=True).stdout

    def commit(self, message: str, who=AGENT, hours: float = 1.0) -> None:
        self.clock += dt.timedelta(hours=hours)
        self.git("add", "-A")
        self.git("commit", "-q", "--allow-empty", "-m", message, who=who)

    def write(self, rel: str, text: str) -> Path:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def approve(self, path: Path, key: str, role: str, hours: float) -> None:
        self.clock += dt.timedelta(hours=hours)
        name, email = PEOPLE[key]
        original, workitems.today = workitems.today, lambda: self.clock.date().isoformat()
        try:
            art = workitems.approve(path, self.root, f"{name} <{email}>", role)
        finally:
            workitems.today = original
        self.commit(f"{art.work_id} {art.kind}: approved by {name} ({role}) -> {art.status}", who=(name, email), hours=0)

    def intent(self, title: str, tier: str, problem: str, outcome: str, sources: list[tuple[str, str]]) -> Path:
        path = workitems.new_work(self.root, title, "{} <{}>".format(*PEOPLE["po"]), tier, year=2026)
        text = path.read_text()
        src = "\n".join(f"  - kind: {k}\n    ref: \"{r}\"" for k, r in sources)
        text = text.replace("sources: []", "sources:\n" + src)
        text = text.replace("## Problem\n", f"## Problem\n{problem}\n", 1).replace("## Desired outcome\n", f"## Desired outcome\n{outcome}\n", 1)
        path.write_text(text)
        workitems.submit(path, self.root)
        self.commit(f"{artifacts.load(path, self.root).work_id} intent: proposed", hours=2)
        return path

    def spec(self, intent: Path, criteria: list[str], design: str) -> Path:
        path = workitems.add_stage(self.root, intent.parent, "spec")
        acs = "\n".join(f"- AC-{i} {c}" for i, c in enumerate(criteria, 1))
        text = path.read_text().replace("## Acceptance criteria\n", f"## Acceptance criteria\n{acs}\n", 1)
        text = text.replace("## Design\n", f"## Design\n{design}\n", 1).replace("skills_applied: []", "skills_applied: [api-design]")
        path.write_text(text)
        workitems.submit(path, self.root)
        self.commit(f"{artifacts.load(path, self.root).work_id} spec: proposed", hours=1.5)
        return path

    def plan(self, intent: Path, steps: list[str], done: int = 0) -> Path:
        path = workitems.add_stage(self.root, intent.parent, "plan")
        body = "\n".join(f"- [{'x' if i < done else ' '}] {s}" for i, s in enumerate(steps))
        path.write_text(path.read_text().replace("- [ ] \n", body + "\n", 1))
        workitems.submit(path, self.root)
        self.commit(f"{artifacts.load(path, self.root).work_id} plan: proposed", hours=1)
        return path


def build(root: Path) -> Path:
    if root.exists() and any(root.iterdir()):
        raise FileExistsError(f"{root} is not empty")
    root.mkdir(parents=True, exist_ok=True)
    for name in ("templates", "policy"):
        shutil.copytree(PKG_ROOT / name, root / name)
    d = Demo(root)
    d.git("init", "-q", "-b", "main")
    d.git("config", "commit.gpgsign", "false")
    d.write("README.md", "# demo-shop (sample data)\n\nA sample repository generated by `python3 -m sdlc demo`.\n")
    d.commit("chore: repository with ai-sdlc policy and templates", who=PEOPLE["lead"])

    # W-0001: the full chain, done, with every criterion traced to a test.
    w1 = d.intent("EU checkout latency", "T2", "EU checkout p95 is 1.4 s; SUP-8812 and 37 similar tickets cite timeouts.",
                  "EU checkout p95 under 800 ms for 7 days.", [("ticket", "SUP-8812"), ("metric", "checkout.p95_ms > 1200 (7d)")])
    d.approve(w1, "po", "product-owner", 5)
    s1 = d.spec(w1, ["EU p95 under 800 ms", "no drop in payment success rate"], "Edge cache in front of the price service.")
    d.approve(s1, "arch", "architect", 9)
    p1 = d.plan(w1, ["add edge cache", "invalidate on price events", "p95 panel"], done=3)
    d.approve(p1, "lead", "tech-lead", 3)
    d.write("src/checkout/cache.py", "TTL_SECONDS = 30\n")
    d.write("tests/test_checkout.py", "def test_eu_p95():  # W-0001:AC-1\n    pass\n\n\ndef test_success_rate():  # W-0001:AC-2\n    pass\n")
    d.commit("W-0001 add EU edge cache with tests", hours=4)
    workitems.complete(p1, root)
    d.commit("W-0001 plan: done", who=PEOPLE["lead"], hours=20)

    # W-0002: T3 refund work, spec waiting for its second approver.
    w2 = d.intent("Refund webhook retries", "T3", "Refund webhooks are dropped on 5xx; finance reconciles 1.2% by hand.",
                  "Zero dropped refund webhooks over 30 days.", [("ticket", "FIN-311"), ("metric", "refund.webhook.dropped")])
    d.approve(w2, "po", "product-owner", 6)
    s2 = d.spec(w2, ["retry with backoff up to 24 h", "idempotent refund handler", "alert after 3 failures"],
                "Outbox table plus a retry worker in payments/.")
    d.approve(s2, "arch", "architect", 4)

    # W-0003: freshly proposed intent, waiting for the product owner.
    d.intent("Search result pagination", "T1", "Search returns at most 50 results; 14 feedback items ask for more.",
             "Users can page through all results.", [("feedback", "NPS-2026-08 search")])

    # W-0004: plan accepted, in build; one of two criteria traced so far.
    w4 = d.intent("Dark mode for the dashboard", "T1", "Support staff work night shifts; 22 requests for a dark theme.",
                  "Dashboard follows the OS theme.", [("feedback", "support-survey-q3")])
    d.approve(w4, "po", "product-owner", 3)
    s4 = d.spec(w4, ["follows prefers-color-scheme", "contrast AA in both themes"], "Token-based theme switch.")
    d.approve(s4, "arch", "architect", 2)
    p4 = d.plan(w4, ["theme tokens", "dark palette", "contrast check"], done=1)
    d.approve(p4, "lead", "tech-lead", 5)

    # Maintain: a control band breach opens an incident and a proposed follow-up intent.
    d.write("bands/checkout.json", json.dumps({"service": "checkout", "owner": "{} <{}>".format(*PEOPLE["po"]), "tier": "T2",
                                               "bands": [{"name": "p95-latency", "metric": "checkout.p95_ms", "max": 800, "for": 3}]}, indent=2))
    d.commit("ops: control bands for checkout", who=PEOPLE["lead"], hours=6)
    d.clock += dt.timedelta(hours=30)
    breach = bands.check(bands.load_bands(root), {"checkout.p95_ms": [760, 830, 870, 910]})[0][0]
    bands.open_loop(root, breach, d.clock)
    d.commit("maintain: checkout p95 band breached", hours=0)

    # A feature branch in progress, so the branch check has something to judge.
    d.git("checkout", "-q", "-b", "feature/w-0004-dark-mode")
    d.write("src/dashboard/theme.css", ":root { color-scheme: light dark; }\n")
    d.write("tests/test_theme.py", "def test_follows_os_theme():  # W-0004:AC-1\n    pass\n")
    d.commit("W-0004 theme tokens and OS theme test", hours=3)
    return root
